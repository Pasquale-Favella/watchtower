import { expect, test } from '@playwright/test'

import { dismissOnboarding, withApp } from './app'

test('shared compact settings preserve the active vertical and saved preferences', async () => {
  await withApp(async ({ window }) => {
    await dismissOnboarding(window)
    const trigger = window.getByRole('button', { name: 'Settings', exact: true })
    await trigger.click()
    const dialog = window.getByRole('dialog', { name: 'Settings', exact: true })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('navigation', { name: 'Settings groups' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Analytics', exact: true }).click()
    await expect(dialog.getByLabel('Default period', { exact: true })).toBeVisible()
    await dialog.getByRole('button', { name: 'Workspace', exact: true }).click()
    await expect(dialog.getByRole('button', { name: 'Agent defaults', exact: true })).toBeVisible()
    await dialog.getByRole('combobox', { name: 'Default access mode', exact: true }).click()
    await window.getByRole('option', { name: 'Auto-accept edits', exact: true }).click()
    await window.screenshot({ path: test.info().outputPath('settings-workspace.png') })
    await window.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    await expect(window.getByRole('textbox', { name: 'Prompt', exact: true })).toBeVisible()

    await window.keyboard.press(process.platform === 'darwin' ? 'Meta+,' : 'Control+,')
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: 'General', exact: true }).click()
    await dialog.getByRole('tab', { name: 'Dark', exact: true }).click()
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    await window.reload()
    await expect(trigger).toBeVisible()
    await expect(window.locator('html')).toHaveClass(/dark/)
    await trigger.click()
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: 'Workspace', exact: true }).click()
    await expect(dialog.getByRole('combobox', { name: 'Default access mode', exact: true })).toContainText(
      'Auto-accept edits',
    )
    await dialog.getByRole('button', { name: 'General', exact: true }).click()
    await window.screenshot({ path: test.info().outputPath('settings-general.png') })
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()

    await window.getByRole('button', { name: 'Switch application, Workspace', exact: true }).click()
    await window.getByRole('menuitem', { name: 'Analytics' }).click()
    await expect(window.getByRole('button', { name: 'Overview', exact: true })).toBeVisible()
    await trigger.click()
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: 'Analytics', exact: true }).click()
    await window.screenshot({ path: test.info().outputPath('settings-analytics.png') })
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    await expect(window.getByRole('button', { name: 'Overview', exact: true })).toBeVisible()
    await window.keyboard.press(process.platform === 'darwin' ? 'Meta+k' : 'Control+k')
    await window.getByPlaceholder('Go to a section or run an action...').fill('Settings')
    await window.screenshot({ path: test.info().outputPath('settings-palette.png') })
    await window.getByPlaceholder('Go to a section or run an action...').press('Enter')
    await expect(dialog).toBeVisible()
    await window.setViewportSize({ width: 900, height: 650 })
    const bounds = await dialog.boundingBox()
    expect(bounds?.width).toBeLessThan(900)
    expect(bounds?.height).toBeLessThan(650)
    await expect(dialog.getByRole('button', { name: 'Done', exact: true })).toBeVisible()
    await window.screenshot({ path: test.info().outputPath('settings-compact.png') })
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  })
})
